import { readdirSync, mkdirSync, writeFileSync, readFileSync } from 'node:fs'
import { join } from 'node:path'

const root = join(process.cwd(), 'src', 'experience', 'components')
const levels = ['atoms', 'molecules', 'organisms']

/**
 * The inventory lists every renderable export, not every file: a module can export several
 * components (BlogVisualAtoms), and each one gets its own entry and preview. A component is the
 * default export or a named `export function PascalCase(` / `export const PascalCase = (`.
 */
const defaultExport = /^export default (?:async )?function (\w+)/m
const defaultReference = /^export default (\w+)\s*$/m
const namedExport = /^export (?:function|const) ([A-Z][A-Za-z0-9]*[a-z][A-Za-z0-9]*)\b/gm

const components = levels.flatMap((folder) => readdirSync(join(root, folder), { withFileTypes: true })
  .filter((entry) => entry.isFile() && entry.name.endsWith('.tsx'))
  .flatMap((entry) => {
    const file = entry.name.slice(0, -4)
    const source = readFileSync(join(root, folder, entry.name), 'utf8')
    const base = { level: folder.slice(0, -1), sourcePath: `src/experience/components/${folder}/${entry.name}` }
    const found = []
    if (defaultExport.test(source) || defaultReference.test(source)) found.push({ id: `${folder}/${file}`, name: file, exportName: 'default', ...base })
    for (const match of source.matchAll(namedExport)) found.push({ id: `${folder}/${file}.${match[1]}`, name: match[1], exportName: match[1], ...base })
    return found
  }))

const registryDir = join(process.cwd(), 'src', 'experience', 'registry')
mkdirSync(registryDir, { recursive: true })

function writeIfChanged(target, content) {
  let previous = ''
  try { previous = readFileSync(target, 'utf8') } catch {}
  if (previous !== content) writeFileSync(target, content)
}

writeIfChanged(join(registryDir, 'designInventory.json'), `${JSON.stringify(components, null, 2)}\n`)

// Static imports keep every preview tied to the frontend's actual component module.
const imports = components.map((component, index) => {
  const module = `@/experience/components/${component.level}s/${component.sourcePath.split('/').at(-1).slice(0, -4)}`
  return component.exportName === 'default'
    ? `import Specimen${index} from '${module}'`
    : `import { ${component.exportName} as Specimen${index} } from '${module}'`
}).join('\n')
const registry = `'use client'\n// Generated by scripts/generate-design-inventory.mjs. Do not edit.\nimport type { ComponentType } from 'react'\n${imports}\n// Keys stay literal so componentSamples.ts must provide a typed sample for every entry.\nexport const componentSpecimens = {\n${components.map((component, index) => `  '${component.id}': Specimen${index},`).join('\n')}\n} satisfies Record<string, ComponentType<any>>\n`
writeIfChanged(join(registryDir, 'componentSpecimens.ts'), registry)
